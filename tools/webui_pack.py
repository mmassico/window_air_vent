#!/usr/bin/env python3
"""Pack the web pages of firmware/webui into C headers for the firmware.

Usage: python tools/webui_pack.py   (run from the window-vent folder; again after any change in firmware/webui/web)
web/index.html: its stylesheets and scripts are inlined, then the page is gzipped into WebPage.h (WEB_INDEX_GZ).
web/setup.html (self-contained): gzipped into SetupPage.h (WEB_SETUP_GZ).
The server sends them as they are, with Content-Encoding: gzip.
"""
import gzip
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP = os.path.join(ROOT, "firmware", "webui")
WEB = os.path.join(APP, "web")


def read(path):
    with open(os.path.join(WEB, path), encoding="utf-8") as fh:
        return fh.read()


def inline(html):
    def css(m):
        return "<style>\n" + read(m.group(1)) + "\n</style>"

    def js(m):
        code = read(m.group(1))
        assert "</script" not in code.lower(), m.group(1) + " would close its inline <script>"
        return "<script>\n" + code + "\n</script>"

    html = re.sub(r'<link rel="stylesheet" href="([^"]+)">', css, html)
    html = re.sub(r'<script src="([^"]+)"></script>', js, html)
    return html


def header(name, var, data, source):
    gz = gzip.compress(data.encode("utf-8"), compresslevel=9, mtime=0)
    lines = [f"// Generated by tools/webui_pack.py from {source}: do not edit.",
             f"// {len(data)} bytes of HTML, {len(gz)} gzipped.",
             "#pragma once",
             "#include <stdint.h>",
             "",
             f"static const uint8_t {var}[] = {{"]
    for i in range(0, len(gz), 20):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in gz[i:i + 20]) + ",")
    lines.append("};")
    with open(os.path.join(APP, name), "w", encoding="ascii", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {name}: {len(data)} bytes, {len(gz)} gzipped")


header("WebPage.h", "WEB_INDEX_GZ", inline(read("index.html")), "web/index.html (with its CSS and scripts)")
header("SetupPage.h", "WEB_SETUP_GZ", read("setup.html"), "web/setup.html")
